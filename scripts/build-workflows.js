#!/usr/bin/env node
'use strict';

/**
 * Generates the n8n workflow JSON files in /workflows from the tested modules in /src and the
 * Code-node glue in /scripts/node-code.
 *
 *   node scripts/build-workflows.js           write workflows/*.json
 *   node scripts/build-workflows.js --check   verify workflows/*.json are current, every Code node compiles,
 *                                             and the output is sanitized (no credential IDs, webhookIds, instanceIds)
 *
 * Edit src/ and scripts/node-code/, never the generated JSON.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');

// ---------- code inlining ----------

const stripModule = (source) =>
  source
    .replace(/\/\/ @build:strip-start[\s\S]*?\/\/ @build:strip-end\n?/g, '')
    .replace(/^'use strict';\s*\n/m, '')
    .trim();

function assembleCode(modules, glueFile) {
  return (
    [
      '// Generated by scripts/build-workflows.js - edit src/ and scripts/node-code/, not this node.',
      ...modules.map((m) => `// ---- src/${m}.js ----\n${stripModule(read(`src/${m}.js`))}`),
      `// ---- node logic (scripts/node-code/${glueFile}) ----\n${read(`scripts/node-code/${glueFile}`).trim()}`,
    ].join('\n\n') + '\n'
  );
}

// ---------- n8n node builders ----------

const uid = (name) => {
  const h = crypto.createHash('md5').update(name).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`;
};

// Placeholder credential references: NAME ONLY (no IDs). n8n asks you to map them on import.
const CRED = {
  hubspot: { hubspotAppToken: { name: 'YOUR_HUBSPOT_CREDENTIAL' } },
  apollo: { httpHeaderAuth: { name: 'YOUR_APOLLO_CREDENTIAL' } },
  llm: { httpHeaderAuth: { name: 'YOUR_LLM_CREDENTIAL' } },
  webhook: { httpHeaderAuth: { name: 'YOUR_WEBHOOK_AUTH_CREDENTIAL' } },
};

const node = (name, type, typeVersion, position, parameters, extra) =>
  Object.assign({ parameters, id: uid(name), name, type, typeVersion, position }, extra || {});

const code = (name, position, modules, glueFile, notes) =>
  node(name, 'n8n-nodes-base.code', 2, position, { jsCode: assembleCode(modules, glueFile) }, notes ? { notes, notesInFlow: true } : {});

/**
 * Generic HTTP Request node.
 * onError: 'continueErrorOutput' adds a 2nd (error) output; 'continueRegularOutput' keeps going with the error in the item.
 */
function http(name, position, o) {
  const parameters = { method: o.method || 'POST', url: o.url, options: o.timeout ? { timeout: o.timeout } : {} };
  if (o.cred && o.cred.hubspotAppToken) Object.assign(parameters, { authentication: 'predefinedCredentialType', nodeCredentialType: 'hubspotAppToken' });
  else if (o.cred) Object.assign(parameters, { authentication: 'genericCredentialType', genericAuthType: 'httpHeaderAuth' });
  else parameters.authentication = 'none';
  Object.assign(parameters, { sendBody: true, specifyBody: 'json', jsonBody: o.body });

  const extra = { onError: o.onError || 'continueErrorOutput' };
  if (o.cred) extra.credentials = o.cred;
  if (o.retry) Object.assign(extra, { retryOnFail: true, maxTries: o.retry, waitBetweenTries: 2000 });
  if (o.notes) Object.assign(extra, { notes: o.notes, notesInFlow: true });
  return node(name, 'n8n-nodes-base.httpRequest', 4.2, position, parameters, extra);
}

const ifBool = (name, position, conditions) =>
  node(name, 'n8n-nodes-base.if', 2.2, position, {
    conditions: {
      options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 2 },
      conditions: conditions.map(([left, operation], i) => ({
        id: uid(`${name}-${i}`),
        leftValue: left,
        rightValue: '',
        operator: { type: 'boolean', operation, singleValue: true },
      })),
      combinator: 'and',
    },
    options: {},
  });

const noOp = (name, position, notes) => node(name, 'n8n-nodes-base.noOp', 1, position, {}, notes ? { notes, notesInFlow: true } : {});
const sticky = (name, position, width, height, content, color) => node(name, 'n8n-nodes-base.stickyNote', 1, position, { content, height, width, color: color || 4 });

function workflow(name, nodes, links) {
  const connections = {};
  for (const [from, to, outputIndex = 0] of links) {
    connections[from] = connections[from] || { main: [] };
    while (connections[from].main.length <= outputIndex) connections[from].main.push([]);
    connections[from].main[outputIndex].push({ node: to, type: 'main', index: 0 });
  }
  // Sanitized: no instanceId, no versionId, no webhookId, no credential IDs, no execution metadata.
  return { name, nodes, pinData: {}, connections, active: false, settings: { executionOrder: 'v1' }, tags: [] };
}

