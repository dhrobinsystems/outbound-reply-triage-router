// ---------- main ----------

const OUTPUTS = {
  'workflows/01-reply-triage-router.json': buildTriage,
  'workflows/02-error-handler.json': buildErrorHandler,
};

function compileCheck(wf, file) {
  for (const n of wf.nodes.filter((x) => x.type === 'n8n-nodes-base.code')) {
    try {
      new Function('$input', '$', '$env', '$getWorkflowStaticData', n.parameters.jsCode);
    } catch (e) {
      throw new Error(`${file} > "${n.name}" does not compile: ${e.message}`);
    }
  }
}

function sanitizeCheck(text, file) {
  const problems = [];
  const wf = JSON.parse(text);
  if (/"webhookId"|"instanceId"|"versionId"/.test(text)) problems.push('contains webhookId / instanceId / versionId');
  for (const n of wf.nodes) {
    for (const [type, ref] of Object.entries(n.credentials || {})) {
      if (ref.id !== undefined) problems.push(`${n.name}: credential "${type}" has an id`);
      if (!/^YOUR_[A-Z_]+_CREDENTIAL$/.test(ref.name)) problems.push(`${n.name}: credential name "${ref.name}" is not a YOUR_*_CREDENTIAL placeholder`);
    }
  }
  if (wf.active !== false) problems.push('workflow must ship inactive');
  if (/hooks\.slack\.com|xox[bpas]-|pat-[a-z]{2}\d?-[0-9a-f-]{16,}|sk-[A-Za-z0-9]{20,}/i.test(text)) problems.push('looks like a secret/URL is embedded');
  if (problems.length) throw new Error(`${file} is not sanitized:\n  - ${problems.join('\n  - ')}`);
}

const checkOnly = process.argv.includes('--check');
let failed = false;
for (const [file, build] of Object.entries(OUTPUTS)) {
  const wf = build();
  compileCheck(wf, file);
  const text = JSON.stringify(wf, null, 2) + '\n';
  sanitizeCheck(text, file);
  const target = path.join(ROOT, file);
  if (checkOnly) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current !== text) {
      console.error(`OUT OF DATE: ${file} - run "npm run build"`);
      failed = true;
    } else {
      console.log(`ok  ${file} (${wf.nodes.length} nodes)`);
    }
  } else {
    fs.writeFileSync(target, text);
    console.log(`wrote ${file} (${wf.nodes.length} nodes)`);
  }
}
process.exit(failed ? 1 : 0);
